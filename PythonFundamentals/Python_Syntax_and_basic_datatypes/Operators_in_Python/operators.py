a = 5
b = 3
print(5 & 3)
print(5 | 3)
print(5 ^ 3)
print(~5)
print(5 << 1)
print(5 >> 1)
print(a / b)

# Tricky operations
print(f"1. {5 + 2 * 3}")
print(f"2. {(5 + 2) * 3}")
print(f"3. {2 ** 3 ** 2}")
print(f"4. {True + 5}") # true value is 1 so 1 + 5 => 6
print(f"5. {False + 10}") #
print(f"6. {10 and 0}")
print(f"7. {10 and 5}")
print(f"8. {0 or 5}")
print(f"9. {0 or 5 or 10}")
print(f"10. {not 0}")
print(f"11. {not 10}")
print(f"12. {5 > 3 > 1}")
print(f"13. {5 > 3 < 4}")
print(f"14. {5 == 5.0}")
print(f"15. {5 is 5.0}")
print(f"16. {-5 % 3}")
print(f"17. {5 % -3}")

